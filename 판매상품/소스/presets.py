def rules_for(p):
    roles = dict(ROLE_DEFAULT); roles.update(p.get("roles", {}))
    inc = {n for n, _ in p["income"]}; exp = {e[0] for e in p["expense"]}
    common = []
    for role, kws in COMMON:
        cat = roles.get(role)
        if cat and (cat in inc or cat in exp or cat == "제외"):
            common += [(k, cat) for k in kws]
    out = p["pre"] + common + p["post"]
    for k, c in out:
        assert c in inc or c in exp or c == "제외", (k, c)
    return out


